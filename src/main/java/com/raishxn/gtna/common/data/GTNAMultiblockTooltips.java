package com.raishxn.gtna.common.data;

import com.gregtechceu.gtceu.api.machine.MachineDefinition;
import com.gregtechceu.gtceu.api.machine.MultiblockMachineDefinition;
import com.gregtechceu.gtceu.api.registry.GTRegistries;

import net.minecraft.network.chat.Component;

import com.raishxn.gtna.GTNACORE;

/**
 * Standard tooltip of every GTNA multiblock, in a fixed order:
 *
 * <pre>
 * Machine Type: &lt;type&gt;
 * &lt;flavor line&gt;
 * ──────────
 * &lt;description&gt;
 * ──────────
 * ▸ advantages / ▸ numbers / ▸ restrictions
 * Source: &lt;addon&gt;
 * </pre>
 *
 * <p>
 * The lines are {@code gtna.machine.<id>.tooltip.N} lang keys (English in
 * {@link GTNAMultiblockTooltipText}, both languages generated by {@code tools/apply_multiblock_tooltips.py}).
 * Runs after every other tooltip pass and replaces the builder, so the multiblock shows only this layout.
 * Machines without a declared origin in {@link GTNASources} are attributed to GTNA.
 */
public final class GTNAMultiblockTooltips {

    private GTNAMultiblockTooltips() {}

    public static void applyAll() {
        for (MachineDefinition definition : GTRegistries.MACHINES) {
            if (!(definition instanceof MultiblockMachineDefinition) ||
                    !GTNACORE.MOD_ID.equals(definition.getId().getNamespace())) {
                continue;
            }
            String path = definition.getId().getPath();
            String[] english = GTNAMultiblockTooltipText.ENGLISH.get(path);
            if (english == null) {
                continue;
            }
            int lines = english.length;
            String source = GTNASources.sourceOf(path);
            String sourceId = source != null ? source : GTNASources.GTNA;
            definition.setTooltipBuilder((stack, components) -> {
                for (int i = 0; i < lines; i++) {
                    components.add(Component.translatable("gtna.machine." + path + ".tooltip." + i));
                }
                components.add(GTNASources.line(sourceId));
            });
        }
    }

    /** Whether a GTNA multiblock registry path has a standard tooltip. */
    public static boolean has(String path) {
        return GTNAMultiblockTooltipText.ENGLISH.containsKey(path);
    }
}
