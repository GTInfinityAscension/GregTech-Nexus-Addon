"""Checks every number in the bullet (▸) lines of the standard multiblock tooltips against an explicit claim.

tools/multiblock_tooltips/number_claims.json (built by build_number_claims.py) maps machine -> number ->
a list of {file, pattern, expr}. A number is confirmed only when it has claims and every regex matches its file. There is
no fallback to "the digits appear somewhere". Writes docs/reports/multiblock-tooltips-trace.md; exit 1 on any gap.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GTCEU = Path("/home/raishxn/MineProjects/GTCEu-7.5.3/src/main/java")
SPEC_DIR = ROOT / "tools/multiblock_tooltips"
CLAIMS = json.loads((SPEC_DIR / "number_claims.json").read_text())
NOT_SPECS = {"number_claims.json"}


def read(ref):
    path = GTCEU / ref[len("gtceu:"):] if ref.startswith("gtceu:") else ROOT / ref
    if not path.exists():
        raise SystemExit(f"claim file does not exist: {ref}")
    return path.read_text()


def main():
    specs = {}
    for f in sorted(SPEC_DIR.glob("*.json")):
        if f.name not in NOT_SPECS:
            specs.update(json.loads(f.read_text()))
    rows, bad = [], 0
    for mid in sorted(specs):
        spec = specs[mid]
        seen = []
        for line in spec["pro"] + spec["num"] + spec["con"]:
            for n in re.findall(r"(?<![A-Za-z\d])\d[\d,]*(?:\.\d+)?", re.sub(r"§.", "", line)):
                key = n.replace(",", "")
                if key in seen:
                    continue
                seen.append(key)
                claims = CLAIMS.get(mid, {}).get(key)
                if not claims:
                    rows.append((mid, n, "UNCONFIRMED", "no claim"))
                    bad += 1
                    continue
                failed = [c for c in claims if re.search(c["pattern"], read(c["file"])) is None]
                evidence = "; ".join(f"{c['expr']} — `{c['file']}`" for c in claims)
                if failed:
                    evidence += " (pattern not found: " + ", ".join(c["expr"] for c in failed) + ")"
                rows.append((mid, n, "UNCONFIRMED" if failed else "confirmed", evidence))
                bad += bool(failed)
    out = ["# Multiblock tooltip number trace", "",
           "Generated by `tools/trace_multiblock_tooltip_numbers.py`. Each number of each ▸ line has an explicit "
           "claim (file + regex); digits that are part of a name (AE2, T1) are not numbers in `tools/multiblock_tooltips/number_claims.json`; it is confirmed only when the "
           "regex matches that file.", "", "| id | Number | Status | Evidence |", "|---|---|---|---|"]
    out += [f"| `{m}` | {n} | {s} | {e.replace('|', '/')} |" for m, n, s, e in rows]
    (ROOT / "docs/reports/multiblock-tooltips-trace.md").write_text("\n".join(out) + "\n")
    print(f"{len(specs)} machines, {len(rows)} numbers, {bad} unconfirmed")
    for m, n, s, e in rows:
        if s != "confirmed":
            print(" ", m, n, e)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
