"""Builds the standard multiblock tooltips from tools/multiblock_tooltips/*.json.

Each JSON entry describes one multiblock (English plus a "pt" block for pt_br):

    type   Machine Type value          flavor  one-line lore / joke
    desc   description lines           pro     advantages (green)
    num    numbers (aqua)              con     restrictions (red)

`*text*` marks a highlight: gold inside the description, yellow inside the bullet lines.

Outputs:
  * src/main/java/com/raishxn/gtna/common/data/GTNAMultiblockTooltipText.java (English, read by the lang
    datagen and by GTNAMultiblockTooltips for the line count)
  * src/main/resources/assets/gtna/lang/pt_br.json (gtna.machine.<id>.tooltip.N replaced)

Run with --check to only validate.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = ROOT / "tools/multiblock_tooltips"
JAVA = ROOT / "src/main/java/com/raishxn/gtna/common/data/GTNAMultiblockTooltipText.java"
PT_BR = ROOT / "src/main/resources/assets/gtna/lang/pt_br.json"

SEPARATOR = "§b§m" + " " * 56
MAX_LEN = 72
FIELDS = ("type", "flavor", "desc", "pro", "num", "con")
LABELS = {"en": "Machine Type: ", "pt": "Tipo de Máquina: "}


def highlight(text, base, accent):
    if text.count("*") % 2:
        raise ValueError(f"unbalanced * in: {text}")
    return re.sub(r"\*(.+?)\*", lambda m: f"{accent}{m.group(1)}{base}", text)


def plain(text):
    return re.sub(r"§.", "", text)


def render(spec, lang):
    lines = [LABELS[lang] + "§e" + spec["type"], "§7§o" + spec["flavor"], SEPARATOR]
    lines += ["§7" + highlight(t, "§7", "§6") for t in spec["desc"]]
    lines.append(SEPARATOR)
    lines += ["§a▸ " + highlight(t, "§a", "§e") for t in spec["pro"]]
    lines += ["§b▸ " + highlight(t, "§b", "§e") for t in spec["num"]]
    lines += ["§c▸ " + highlight(t, "§c", "§e") for t in spec["con"]]
    return lines


def load():
    specs = {}
    for path in sorted(SPEC_DIR.glob("*.json")):
        if path.name == "number_claims.json":  # number-trace data, not a tooltip spec
            continue
        for mid, spec in json.loads(path.read_text()).items():
            if mid in specs:
                raise SystemExit(f"duplicate machine {mid} in {path.name}")
            specs[mid] = spec
    return specs


def validate(specs):
    errors = []
    flavors = {}
    for mid, spec in specs.items():
        for lang, data in (("en", spec), ("pt", spec.get("pt"))):
            if data is None:
                errors.append(f"{mid}: missing pt block")
                continue
            for field in FIELDS:
                value = data.get(field)
                if field not in data or (field in ("type", "flavor", "desc") and not value):
                    errors.append(f"{mid}/{lang}: missing {field}")
            if not (data.get("pro") or data.get("num") or data.get("con")):
                errors.append(f"{mid}/{lang}: no bullet line")
            try:
                rendered = render(data, lang)
            except (ValueError, KeyError, TypeError) as e:
                errors.append(f"{mid}/{lang}: {e}")
                continue
            for line in rendered:
                if line != SEPARATOR and len(plain(line)) > MAX_LEN:
                    errors.append(f"{mid}/{lang}: line too long ({len(plain(line))}): {plain(line)}")
            key = (lang, data.get("flavor"))
            if key in flavors:
                errors.append(f"{mid}/{lang}: flavor repeats {flavors[key]}")
            flavors[key] = mid
            if lang == "en" and len(data.get("desc", [])) > 3:
                errors.append(f"{mid}: description has more than 3 lines")
        if len(render(spec, "en")) != len(render(spec["pt"], "pt")):
            errors.append(f"{mid}: en and pt line counts differ")
    return errors


def java_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_java(specs):
    out = [
        "package com.raishxn.gtna.common.data;",
        "",
        "import java.util.LinkedHashMap;",
        "import java.util.Map;",
        "",
        "/**",
        " * English text of the standard multiblock tooltips, generated by {@code tools/apply_multiblock_tooltips.py}",
        " * from {@code tools/multiblock_tooltips/*.json}. Do not edit by hand.",
        " */",
        "public final class GTNAMultiblockTooltipText {",
        "",
        "    public static final Map<String, String[]> ENGLISH = new LinkedHashMap<>();",
        "",
        "    static {",
    ]
    for mid in sorted(specs):
        out.append(f"        ENGLISH.put({java_string(mid)}, new String[] {{")
        for line in render(specs[mid], "en"):
            out.append(f"                {java_string(line)},")
        out.append("        });")
    out += ["    }", "", "    private GTNAMultiblockTooltipText() {}", "}", ""]
    JAVA.write_text("\n".join(out))


def write_pt(specs):
    data = json.loads(PT_BR.read_text())
    ids = "|".join(re.escape(m) for m in specs)
    old = re.compile(rf"^gtna\.(machine\.({ids})\.tooltip(\.\d+)?|gto_tooltip\.({ids})\.\d+)$")
    data = {k: v for k, v in data.items() if not old.match(k)}
    # Appended in machine order; the rest of the file keeps its hand-maintained order.
    for mid in sorted(specs):
        for i, line in enumerate(render(specs[mid]["pt"], "pt")):
            data[f"gtna.machine.{mid}.tooltip.{i}"] = line
    PT_BR.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def main():
    specs = load()
    errors = validate(specs)
    for e in errors:
        print("ERROR", e)
    if errors:
        sys.exit(1)
    print(f"{len(specs)} multiblock tooltips valid")
    if "--check" not in sys.argv:
        write_java(specs)
        write_pt(specs)
        print("wrote", JAVA.relative_to(ROOT), "and", PT_BR.relative_to(ROOT))


if __name__ == "__main__":
    main()
