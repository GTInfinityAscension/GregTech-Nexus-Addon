"""Ports GTOCore recipes of GTO-only recipe types into a GTNA datagen class.

Usage: python3 tools/port_gto_recipes.py

For each (GTO source file, GTO recipe type constant) in SOURCES, every
`<TYPE>.recipeBuilder("id") ... .save();` / `.builder("id")` block is copied with:
  * the type swapped for `GTNARecipeType.<TYPE>` and the id for `GTNACORE.id("<id>")`;
  * `.save()` -> `.save(provider)`;
  * `.outputFluids(Mat, n)` -> `.outputFluids(Mat.getFluid(n))`.
A block is skipped (and reported) when it references GTO content (GTO*, gtocore), research/scanner data,
custom conditions, string item ids or anything in SKIP_TOKENS: GTNA ships only recipes whose inputs and
outputs exist in GTCEu/GTNA. Output: src/main/java/com/raishxn/gtna/data/recipe/GTNAGTORecipes.java
plus a report in docs/reports/gto-recipe-port.md.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GTO = ROOT.parent / "GTOCore-Main/src/main/java/com/gtocore/data/recipe"
OUT = ROOT / "src/main/java/com/raishxn/gtna/data/recipe/GTNAGTORecipes.java"
REPORT = ROOT / "docs/reports/gto-recipe-port.md"

SOURCES = [
    ("classified/PCBFactory.java", "PCB_FACTORY_RECIPES"),
    ("classified/ArcGenerator.java", "ARC_GENERATOR_RECIPES"),
    ("classified/PlasmaCondenser.java", "PLASMA_CONDENSER_RECIPES"),
    ("classified/SpaceProbeSurfaceReception.java", "SPACE_PROBE_SURFACE_RECEPTION_RECIPES"),
]
SKIP_TOKENS = ["GTO", "gtocore", "scanner(", "researchStation", "addCondition", "notConsumable(\"",
               "inputItems(\"", "outputItems(\"", "TagUtils", "RegistriesUtils", "Wrapper", "MarkerMaterials",
               "addData(", "blastFurnaceTemp", "dimension(", "ChemicalHelper", "AEItems",
               "CustomTags", "DDItems", "ModItems", "inputItemsRanged", "chancedOutput", "chancedInput"]
# Symbols the compiler rejected on a previous run (filled in by hand after a failed compile).
UNKNOWN = set()

BLOCK = re.compile(r"(\b[A-Z_]+_RECIPES)\.(?:recipeBuilder|builder)\(\s*\"([^\"]+)\"\s*\)(.*?)\.save\(\s*\)\s*;", re.S)
OUT_FLUID = re.compile(r"\.outputFluids\(\s*([A-Za-z_][\w.]*)\s*,\s*([^()]+?)\)")


def convert(type_name, rid, body):
    for token in SKIP_TOKENS:
        if token in body:
            return None, token
    for symbol in UNKNOWN:
        if re.search(r"\b" + re.escape(symbol) + r"\b", body):
            return None, symbol
    body = OUT_FLUID.sub(lambda m: f".outputFluids({m.group(1)}.getFluid({m.group(2)}))", body)
    return (f"        GTNARecipeType.{type_name}.recipeBuilder(GTNACORE.id(\"{rid}\")){body.rstrip()}\n"
            f"                .save(provider);\n"), None


def main():
    lines, report = [], ["# GTO recipe port (tools/port_gto_recipes.py)", ""]
    for rel, type_name in SOURCES:
        text = (GTO / rel).read_text()
        ported, skipped = 0, []
        for match in BLOCK.finditer(text):
            if match.group(1) != type_name:
                continue
            code, reason = convert(type_name, match.group(2), match.group(3))
            if code is None:
                skipped.append(f"`{match.group(2)}` ({reason})")
                continue
            lines.append(code)
            ported += 1
        report.append(f"## {type_name} ({rel})")
        report.append(f"- ported: {ported}")
        report.append(f"- skipped: {len(skipped)}" + ("" if not skipped else ": " + ", ".join(skipped)))
        report.append("")
    OUT.write_text(TEMPLATE.replace("%BODY%", "".join(lines)))
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(report) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} recipes) and {REPORT.relative_to(ROOT)}")


