"""Extracts GTOCore inline FactoryBlockPattern aisles into GTNAGTOPatterns.java (string data only).

The block mapping (`where`) stays hand-written next to each machine. Run: python3 tools/extract_gto_inline_patterns.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GTO = ROOT.parent / "GTOCore-Main/src/main/java/com/gtocore/common"
OUT = ROOT / "src/main/java/com/raishxn/gtna/common/data/multiblock/GTNAGTOPatterns.java"

# (constant, file, marker that starts the segment, marker that ends it)
SOURCES = [
    ("PCB_FACTORY_T1", "machine/multiblock/electric/PCBFactoryMachine.java", "default ->", ".build();"),
    ("PCB_FACTORY_T2", "machine/multiblock/electric/PCBFactoryMachine.java", "case 2 ->", ".build();"),
    ("PCB_FACTORY_T3", "machine/multiblock/electric/PCBFactoryMachine.java", "case 3 ->", ".build();"),
    ("COMPOUND_EXTREME_COOLING_PLASMA", "machine/multiblock/electric/processing/CompoundExtremeCoolingMachine.java",
     "if (t == 1) {", "} else {"),
    ("COMPOUND_EXTREME_COOLING_VACUUM", "machine/multiblock/electric/processing/CompoundExtremeCoolingMachine.java",
     "} else {", "return builder.build();"),
    ("HYPER_REACTOR", "data/machines/GeneratorMultiblock.java", "multiblock(\"hyper_reactor\"", ".build())"),
    ("SUPERCOMPUTING_CENTER", "data/machines/ExResearchMachines.java", "multiblock(\"supercomputing_center\"",
     ".build())"),
    ("DATA_CENTER", "data/machines/ExResearchMachines.java", "multiblock(\"data_center\"", ".build())"),
    ("ANALYSIS_AND_RESEARCH_CENTER", "data/machines/ExResearchMachines.java",
     "multiblock(\"analysis_and_research_center\"", ".build())"),
]


def main():
    parts = []
    for name, rel, start, end in SOURCES:
        src = (GTO / rel).read_text()
        i = src.index(start)
        j = src.index(end, i + len(start))
        aisles = re.findall(r"\.aisle\(((?:\s*\"[^\"]*\"\s*,?)+)\)", src[i:j])
        rows = ["{ " + ", ".join(re.findall(r"\"[^\"]*\"", a)) + " }" for a in aisles]
        parts.append(f"    public static final String[][] {name} = {{\n" +
                     ",\n".join("            " + r for r in rows) + " };\n")
        print(name, len(rows), "aisles")
    OUT.write_text(TEMPLATE.replace("%BODY%", "\n".join(parts)))


TEMPLATE = """package com.raishxn.gtna.common.data.multiblock;

import com.gregtechceu.gtceu.api.pattern.FactoryBlockPattern;

/**
 * Inline GTOCore patterns (aisle strings only), generated by {@code tools/extract_gto_inline_patterns.py}
 * from GTOCore {@code dc4824d} (CC BY-NC-SA 4.0). Each machine maps the characters next to its definition.
 */
@SuppressWarnings("SpellCheckingInspection")
public final class GTNAGTOPatterns {

    private GTNAGTOPatterns() {}

    public static FactoryBlockPattern aisles(FactoryBlockPattern builder, String[][] aisles) {
        for (String[] aisle : aisles) builder.aisle(aisle);
        return builder;
    }

%BODY%}
"""

if __name__ == "__main__":
    main()
